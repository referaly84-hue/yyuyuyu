export function getClubDossier(teamNameOrId: string): RplClubDossier | null {
  const q = String(teamNameOrId || '').toLowerCase().trim();
  for (const [key, dossier] of Object.entries(RPL_CLUB_DOSSIERS)) {
    if (q.includes(key) || dossier.name.toLowerCase().includes(q) || dossier.id.toLowerCase() === q) {
      return dossier;
    }
  }
  return null;
}

